  let lang = null;
  const listeners = [];

  function detect() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "en" || saved === "zh") return saved;
    } catch (error) { /* storage unavailable */ }
    const nav = (navigator.language || "en").toLowerCase();
    return nav.startsWith("zh") ? "zh" : "en";
  }

  function t(key, vars) {
    const table = lang === "zh" ? zh : en;
    let s = table[key];
    if (s === undefined) s = en[key];
    if (s === undefined) return key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        s = s.split("{" + name + "}").join(String(value));
      }
    }
    return s;
  }

  function applyToDom(root) {
    for (const node of (root || document).querySelectorAll("[data-i18n]")) {
      node.textContent = t(node.getAttribute("data-i18n"));
    }
    for (const node of (root || document).querySelectorAll("[data-i18n-html]")) {
      node.innerHTML = t(node.getAttribute("data-i18n-html"));
    }
    for (const node of (root || document).querySelectorAll("[data-i18n-title]")) {
      node.title = t(node.getAttribute("data-i18n-title"));
    }
  }

  function setLang(next) {
    if (next !== "en" && next !== "zh") return;
    if (next === lang) return;
    lang = next;
    try { localStorage.setItem(STORAGE_KEY, next); } catch (error) { /* ignore */ }
    document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
    applyToDom(document);
    for (const cb of listeners) cb(next);
  }

  function onChange(cb) {
    listeners.push(cb);
  }

  /* Small toggle button; label always offers the other language. */
  function makeLangButton() {
    const button = document.createElement("button");
    button.className = "lang-toggle";
    button.type = "button";
    const sync = () => { button.textContent = t("ui.lang.toggle"); };
    button.addEventListener("click", () => {
      setLang(lang === "zh" ? "en" : "zh");
      sync();
    });
    sync();
    return button;
  }

  lang = detect();
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";

  return {
    t,
    setLang,
    onChange,
    applyToDom,
    makeLangButton,
    get lang() { return lang; },
  };
